"""Boolean34. Даны координаты поля шахматной доски x, y (целые числа, ле- жащие в диапазоне 1–8). Учитывая, что левое нижнее поле доски (1, 1) является черным, проверить истинность высказывания: «Данное поле яв- ляется белым»."""
x, y = map(int, input().split())
condition = (x+y)%2==0
print("TRUE" if condition else "FALSE")
