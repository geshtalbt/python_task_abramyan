"""Boolean39. Даны координаты двух различных полей шахматной доски x1, y1, 14 М. Э. Абрамян. Электронный задачник Programming Taskbook 4.4 x2, y2 (целые числа, лежащие в диапазоне 1–8). Проверить истинность вы- сказывания: «Ферзь за один ход может перейти с одного поля на другое»."""
x1, y1, x2, y2 = map(int, input().split())
condition = x1==x2 or y1==y2 or abs(x1-x2)==abs(y1-y2)
print("TRUE" if condition else "FALSE")
