"""Boolean40. Даны координаты двух различных полей шахматной доски x1, y1, x2, y2 (целые числа, лежащие в диапазоне 1–8). Проверить истинность высказывания: «Конь за один ход может перейти с одного поля на другое». Условный оператор"""
x1, y1, x2, y2 = map(int, input().split())
condition = sorted((abs(x1-x2),abs(y1-y2)))==[1,2]
print("TRUE" if condition else "FALSE")
