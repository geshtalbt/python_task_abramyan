"""Boolean29*. Даны числа x, y, x1, y1, x2, y2. Проверить истинность высказыва- ния: «Точка с координатами (x, y) лежит внутри прямоугольника, левая верхняя вершина которого имеет координаты (x1, y1), правая нижняя — (x2, y2), а стороны параллельны координатным осям»."""
x, y, x1, y1, x2, y2 = map(int, input().split())
condition = min(x1,x2)<x<max(x1,x2) and min(y1,y2)<y<max(y1,y2)
print("TRUE" if condition else "FALSE")
