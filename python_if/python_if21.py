"""If21. Даны целочисленные координаты точки на плоскости. Если точка совпа- дает с началом координат, то вывести 0. Если точка не совпадает с нача- лом координат, но лежит на оси OX или OY, то вывести соответственно 1 или 2. Если точка не лежит на координатных осях, то вывести 3."""
import math
x, y = map(int, input().split())
result = 0 if x==0 and y==0 else 1 if y==0 else 2 if x==0 else 3
print(*result if isinstance(result, tuple) else (result,))
